  const set = new Set(UNIVERSAL_ID_WORDLIST);
  if (set.size !== UNIVERSAL_ID_WORDLIST.length) {
    throw new Error(
      `[WordList] Duplicate words detected. List has ${UNIVERSAL_ID_WORDLIST.length} entries but only ${set.size} are unique.`,
    );
  }
